//! Regenerate the bundled stylesheet or list available fence language tokens.
use syntect::{
    highlighting::ThemeSet,
    html::{ClassStyle, css_for_theme_with_class_style},
};
fn main() {
    if std::env::args().any(|arg| arg == "--syntax-notices") {
        println!("Grammar acknowledgements from two-face 0.5.2+bat-0.26.1\n");
        for license in two_face::acknowledgement::listing().for_syntaxes() {
            println!("{}\n\n{}\n", license.rel_path.display(), license.text);
        }
        return;
    }
    if std::env::args().any(|arg| arg == "--list") {
        for syntax in two_face::syntax::extra_newlines().syntaxes() {
            println!("{}: {}", syntax.name, syntax.file_extensions.join(", "));
        }
        return;
    }
    let themes = ThemeSet::load_defaults();
    let style = ClassStyle::SpacedPrefixed { prefix: "syntax-" };
    println!("/* Generated by Native/Comrak/examples/highlight_styles.rs; Syntect 5.3.0. */");
    print!(
        "{}",
        css_for_theme_with_class_style(&themes.themes["InspiredGitHub"], style).unwrap()
    );
    println!("@media (prefers-color-scheme: dark) {{");
    print!(
        "{}",
        css_for_theme_with_class_style(&themes.themes["base16-ocean.dark"], style).unwrap()
    );
    println!("}}");
}
